// §14.3: imports the shop lists from the external data project and writes one file per country.
// Usage: node scripts/import-shops.mjs <source-folder>   (Node >= 22.18: loads the .ts files directly)
// The source folder is never written in tracked files.
import { execFileSync } from "node:child_process";
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = process.argv[2];
if (!src) {
  console.error("usage: node scripts/import-shops.mjs <source-folder>");
  process.exit(2);
}
const dataDir = path.resolve(src, "data");

// 1) The source must pass its own check first.
try {
  execFileSync(process.execPath, [path.resolve(src, "scripts/check.mjs")], { cwd: path.resolve(src), stdio: "inherit" });
} catch {
  console.error("source check failed: nothing written");
  process.exit(1);
}

const CATEGORIES = ["grocery", "discount", "pharmacy", "beauty", "fashion", "sport", "electronics", "home", "diy", "pet",
  "books", "toys", "fuel", "travel", "restaurant", "department", "optician", "other"];
const norm = (s) => s.normalize("NFKD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/[^a-z0-9]/g, "");
const load = async (f) => import(pathToFileURL(path.join(dataDir, f)).href);

const { INTL } = await load("intl.ts");
const countries = readdirSync(dataDir)
  .filter((f) => /^[a-z]{2}\.ts$/.test(f))
  .map((f) => f.slice(0, 2))
  .sort();

const outDir = path.resolve(here, "../src/data/shops");
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const HEADER = "// Generated by frontend/scripts/import-shops.mjs (§14.3): do not edit by hand.\n";
const clean = (s, domain) => {
  const out = { name: s.name, domain, color: s.color.toUpperCase(), category: s.category };
  if (s.aliases?.length) out.aliases = s.aliases;
  return out; // `format` is never copied (empty at the source)
};

let total = 0;
for (const cc of countries) {
  const { SHOPS } = await load(`${cc}.ts`);
  const merged = [...SHOPS.map((s) => clean(s, s.domain))];
  for (const s of INTL) if (s.domains?.[cc]) merged.push(clean(s, s.domains[cc]));
  const seen = new Set();
  const list = merged.filter((s) => {
    const key = `${norm(s.name)}|${s.domain}`;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
  list.sort((a, b) => CATEGORIES.indexOf(a.category) - CATEGORIES.indexOf(b.category)
    || a.name.localeCompare(b.name, "en", { sensitivity: "base" }));
  total += list.length;
  const body = list.map((s) => `  ${JSON.stringify(s)},`).join("\n");
  writeFileSync(path.join(outDir, `${cc}.ts`),
    `${HEADER}import type { Shop } from "../../types";\n\nexport const SHOPS: Shop[] = [\n${body}\n];\n`);
}

const today = new Date().toISOString().slice(0, 10);
const cases = countries.map((cc) => `    case "${cc}": return (await import("./${cc}")).SHOPS;`).join("\n");
writeFileSync(path.join(outDir, "index.ts"), `${HEADER}import type { Shop } from "../../types";

/** Countries with a shop list (lowercase ISO 3166-1 alpha-2). */
export const SHOP_COUNTRIES: readonly string[] = ${JSON.stringify(countries)};

/** Date of the last import of the shop lists. */
export const SHOPS_UPDATED = "${today}";

/** One chunk per country, loaded only when needed (guided add). Unknown code → []. */
export async function loadShops(cc: string): Promise<Shop[]> {
  switch (cc) {
${cases}
    default: return [];
  }
}
`);

const py = path.resolve(here, "../../custom_components/loyalty_hub/core/shop_countries.py");
const tuple = countries.map((cc) => `"${cc}"`).join(", ");
writeFileSync(py, `"""Countries with a shop list (§14.3). Generated by frontend/scripts/import-shops.mjs: do not edit."""

from __future__ import annotations

SHOP_COUNTRIES: tuple[str, ...] = (${tuple})
SHOPS_UPDATED = "${today}"
`);

console.log(`${countries.length} countries, ${total} shops → src/data/shops/, core/shop_countries.py`);
